// Command androidicons makes the Android launcher icons from build/appicon.png
// (the Wails template ships its own logo in build/android/.../mipmap-*, and
// `wails3 generate icons` only makes the macOS .icns and the Windows .ico).
//
//	go run ./tools/androidicons            (or: wails3 task common:generate:icons)
//
// It writes into build/android/app/src/main/res:
//
//	mipmap-<dpi>/ic_launcher.png             legacy icon (48dp): a rounded dark plate + the art
//	mipmap-<dpi>/ic_launcher_round.png       legacy round icon: a dark circle + the art
//	mipmap-<dpi>/ic_launcher_foreground.png  adaptive icon layer (108dp, the art in the 66dp safe zone)
//	mipmap-anydpi-v26/ic_launcher(_round).xml  adaptive icon (Android 8+): background colour + foreground
//	values/ic_launcher_background.xml        that background colour
//
// Standard library only: the art is cropped to its visible pixels and scaled down with
// an area (box) filter, which is what a downscale needs.
package main

import (
	"flag"
	"fmt"
	"image"
	"image/color"
	"image/draw"
	"image/png"
	"math"
	"os"
	"path/filepath"
)

// plate is the dark background behind the art (the app's --color-bg family).
var plate = color.NRGBA{0x1a, 0x16, 0x12, 0xff}

const plateHex = "#1A1612"

var densities = []struct {
	dir   string
	scale float64 // px per dp
}{
	{"mipmap-mdpi", 1}, {"mipmap-hdpi", 1.5}, {"mipmap-xhdpi", 2}, {"mipmap-xxhdpi", 3}, {"mipmap-xxxhdpi", 4},
}

func main() {
	in := flag.String("in", "build/appicon.png", "source image (square-ish, transparent background)")
	res := flag.String("res", "build/android/app/src/main/res", "the Android res folder")
	flag.Parse()

	src, err := load(*in)
	if err != nil {
		fail(err)
	}
	art := crop(src)

	for _, d := range densities {
		dir := filepath.Join(*res, d.dir)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fail(err)
		}
		legacy := int(math.Round(48 * d.scale))
		adaptive := int(math.Round(108 * d.scale))

		// legacy square: rounded plate (corner 18%), art at 84%
		sq := canvas(legacy)
		roundRect(sq, legacy, 0.18, plate)
		place(sq, art, 0.84)
		save(filepath.Join(dir, "ic_launcher.png"), sq)

		// legacy round: circle plate, art at 78% (inside the circle)
		rd := canvas(legacy)
		circle(rd, legacy, plate)
		place(rd, art, 0.78)
		save(filepath.Join(dir, "ic_launcher_round.png"), rd)

		// adaptive foreground: transparent, art inside the 66dp safe circle of 108dp
		fg := canvas(adaptive)
		place(fg, art, 68.0/108)
		save(filepath.Join(dir, "ic_launcher_foreground.png"), fg)
	}

	anydpi := filepath.Join(*res, "mipmap-anydpi-v26")
	if err := os.MkdirAll(anydpi, 0o755); err != nil {
		fail(err)
	}
	const adaptiveXML = `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/androidicons from build/appicon.png -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`
	write(filepath.Join(anydpi, "ic_launcher.xml"), adaptiveXML)
	write(filepath.Join(anydpi, "ic_launcher_round.xml"), adaptiveXML)
	write(filepath.Join(*res, "values", "ic_launcher_background.xml"), `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/androidicons -->
<resources>
    <color name="ic_launcher_background">`+plateHex+`</color>
</resources>
`)
	fmt.Println("android icons: ok →", *res)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "androidicons:", err)
	os.Exit(1)
}

func load(path string) (*image.NRGBA, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	img, err := png.Decode(f)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	out := image.NewNRGBA(img.Bounds())
	draw.Draw(out, out.Bounds(), img, img.Bounds().Min, draw.Src)
	return out, nil
}

// crop cuts the transparent margins and centres the art on a square.
func crop(img *image.NRGBA) *image.NRGBA {
	b := img.Bounds()
	minX, minY, maxX, maxY := b.Max.X, b.Max.Y, b.Min.X, b.Min.Y
	for y := b.Min.Y; y < b.Max.Y; y++ {
		for x := b.Min.X; x < b.Max.X; x++ {
			if img.NRGBAAt(x, y).A > 8 {
				minX, minY = min(minX, x), min(minY, y)
				maxX, maxY = max(maxX, x+1), max(maxY, y+1)
			}
		}
	}
	if maxX <= minX || maxY <= minY {
		return img
	}
	w, h := maxX-minX, maxY-minY
	side := max(w, h)
	sq := image.NewNRGBA(image.Rect(0, 0, side, side))
	draw.Draw(sq, image.Rect((side-w)/2, (side-h)/2, (side-w)/2+w, (side-h)/2+h), img, image.Pt(minX, minY), draw.Src)
	return sq
}

func canvas(n int) *image.NRGBA { return image.NewNRGBA(image.Rect(0, 0, n, n)) }

// place scales the art to `frac` of the canvas and draws it centred over what is there.
func place(dst, art *image.NRGBA, frac float64) {
	n := dst.Bounds().Dx()
	size := int(math.Round(float64(n) * frac))
	small := scale(art, size)
	off := (n - size) / 2
	draw.Draw(dst, image.Rect(off, off, off+size, off+size), small, image.Point{}, draw.Over)
}

// scale — area-average downscale (premultiplied, so transparent edges don't go dark).
func scale(src *image.NRGBA, size int) *image.NRGBA {
	sw := src.Bounds().Dx()
	out := image.NewNRGBA(image.Rect(0, 0, size, size))
	k := float64(sw) / float64(size)
	for y := 0; y < size; y++ {
		y0, y1 := float64(y)*k, float64(y+1)*k
		for x := 0; x < size; x++ {
			x0, x1 := float64(x)*k, float64(x+1)*k
			var r, g, b, a, wsum float64
			for sy := int(y0); sy < int(math.Ceil(y1)) && sy < sw; sy++ {
				wy := math.Min(y1, float64(sy+1)) - math.Max(y0, float64(sy))
				for sx := int(x0); sx < int(math.Ceil(x1)) && sx < sw; sx++ {
					wx := math.Min(x1, float64(sx+1)) - math.Max(x0, float64(sx))
					w := wx * wy
					c := src.NRGBAAt(sx, sy)
					al := float64(c.A) / 255
					r += float64(c.R) * al * w
					g += float64(c.G) * al * w
					b += float64(c.B) * al * w
					a += al * w
					wsum += w
				}
			}
			if a <= 0 || wsum <= 0 {
				continue
			}
			out.SetNRGBA(x, y, color.NRGBA{
				R: uint8(math.Round(r / a)),
				G: uint8(math.Round(g / a)),
				B: uint8(math.Round(b / a)),
				A: uint8(math.Round(255 * a / wsum)),
			})
		}
	}
	return out
}

// coverage-based shapes (4×4 supersampling for smooth edges)
func shape(dst *image.NRGBA, n int, c color.NRGBA, inside func(x, y float64) bool) {
	const ss = 4
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			hit := 0
			for j := 0; j < ss; j++ {
				for i := 0; i < ss; i++ {
					if inside(float64(x)+(float64(i)+0.5)/ss, float64(y)+(float64(j)+0.5)/ss) {
						hit++
					}
				}
			}
			if hit > 0 {
				cc := c
				cc.A = uint8(int(c.A) * hit / (ss * ss))
				dst.SetNRGBA(x, y, cc)
			}
		}
	}
}

func circle(dst *image.NRGBA, n int, c color.NRGBA) {
	r := float64(n) / 2
	shape(dst, n, c, func(x, y float64) bool { return (x-r)*(x-r)+(y-r)*(y-r) <= r*r })
}

func roundRect(dst *image.NRGBA, n int, corner float64, c color.NRGBA) {
	s := float64(n)
	rad := s * corner
	shape(dst, n, c, func(x, y float64) bool {
		cx := math.Max(rad, math.Min(s-rad, x))
		cy := math.Max(rad, math.Min(s-rad, y))
		return (x-cx)*(x-cx)+(y-cy)*(y-cy) <= rad*rad
	})
}

func save(path string, img image.Image) {
	f, err := os.Create(path)
	if err != nil {
		fail(err)
	}
	defer f.Close()
	if err := (&png.Encoder{CompressionLevel: png.BestCompression}).Encode(f, img); err != nil {
		fail(err)
	}
}

func write(path, s string) {
	if err := os.WriteFile(path, []byte(s), 0o644); err != nil {
		fail(err)
	}
}
